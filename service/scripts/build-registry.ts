/**
 * Turns registry/addons.toml into src/generated/registry.ts, which /v1/registry serves.
 *
 *   node scripts/build-registry.ts [--file <path>]
 *
 * Validates strictly, like the registry check script, and exits 1 on any problem, so a broken
 * registry never reaches a deployment.
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { parseArgs } from "node:util";
import { parse } from "smol-toml";
import { parseRegistry, registryDocument } from "../src/registry.ts";

const root = join(import.meta.dirname, "..");
const { values } = parseArgs({ options: { file: { type: "string" } } });
const file = values.file ?? join(root, "..", "registry", "addons.toml");
const out = join(root, "src", "generated", "registry.ts");

const { entries, problems } = parseRegistry(parse(await readFile(file, "utf8")), { strict: true });
if (problems.length) {
  for (const p of problems) console.error(`${file}: ${p}`);
  process.exit(1);
}

const hash = createHash("sha256").update(JSON.stringify(registryDocument(entries, ""))).digest("hex");
const doc = registryDocument(entries, hash.slice(0, 16));
const text = `// Generated by scripts/build-registry.ts from registry/addons.toml. Do not edit.
import type { RegistryDocument } from "../registry.ts";

export const registryEtag = ${JSON.stringify(`"${doc.version}"`)};
export const registryJson = ${JSON.stringify(JSON.stringify(doc))};
export const registry: RegistryDocument = JSON.parse(registryJson);
`;
await mkdir(dirname(out), { recursive: true });
await writeFile(out, text);
console.log(`Wrote ${entries.length} registry entries (version ${doc.version}).`);
